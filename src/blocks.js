export const BLOCK_TYPES = ["Vacation", "Elective", "Ultrasound"];

const ymdLocal = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

// People off-service for any part of the Mon-Sun week [weekStart, weekEnd), grouped by type.
export function awayInWeek(weekStartDate, weekEndDate) {
  const a = ymdLocal(weekStartDate);
  const last = new Date(weekEndDate); last.setDate(last.getDate() - 1);
  const b = ymdLocal(last);
  const groups = Object.fromEntries(BLOCK_TYPES.map((t) => [t, []]));
  const seen = new Set();
  for (const [s, e, name, pgy, type] of BLOCK_ROWS) {
    if (e < a || s > b) continue;
    const key = `${type}|${name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    groups[type].push({ name, pgy });
  }
  for (const t of BLOCK_TYPES) groups[t].sort((x, y) => x.pgy - y.pgy || x.name.localeCompare(y.name));
  return groups;
}

export function blockDataCovers(weekStartDate) {
  return ymdLocal(weekStartDate) >= "2026-10-26" && ymdLocal(weekStartDate) <= "2027-06-30";
}
